CREATE TABLE file (
    file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    related_type VARCHAR(30) NOT NULL,
    related_id VARCHAR(36) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    stored_name VARCHAR(1024) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_file_related_type CHECK (
        related_type IN ('MEMBER_PROFILE', 'FAQ_ATTACHMENT', 'INQUIRY_ATTACHMENT')
    ),
    CONSTRAINT ck_file_size CHECK (size_bytes >= 1)
);

CREATE INDEX ix_file_related ON file (related_type, related_id);

COMMENT ON TABLE file IS '외부 저장소 파일 메타데이터';
COMMENT ON COLUMN file.file_id IS '파일 식별자';
COMMENT ON COLUMN file.related_type IS '파일 사용처: MEMBER_PROFILE(회원 프로필), FAQ_ATTACHMENT(FAQ 첨부), INQUIRY_ATTACHMENT(문의 첨부)';
COMMENT ON COLUMN file.related_id IS '파일이 연결된 대상 식별자';
COMMENT ON COLUMN file.original_name IS '업로드한 원본 파일명';
COMMENT ON COLUMN file.stored_name IS '외부 저장소에 저장된 파일명';
COMMENT ON COLUMN file.mime_type IS '검증된 파일 MIME 유형';
COMMENT ON COLUMN file.size_bytes IS '파일 크기(바이트)';
COMMENT ON COLUMN file.created_at IS '파일 메타데이터 생성 시각(UTC)';
