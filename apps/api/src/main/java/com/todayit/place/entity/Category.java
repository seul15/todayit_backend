package com.todayit.place.entity;

/** 장소를 이용 목적과 성격에 따라 구분하는 상위 카테고리입니다. */
public enum Category {

  /** 한식, 양식, 일식, 중식, 분식, 브런치 등 식사를 주된 목적으로 하는 음식점입니다. */
  RESTAURANT,

  /** 카페, 베이커리, 디저트 전문점, 제과점 등 음료나 디저트를 즐기는 장소입니다. */
  CAFE_DESSERT,

  /** 이자카야, 와인바, 칵테일바, 펍 등 주류와 함께 시간을 보내는 장소입니다. */
  BAR,

  /** 미술관, 박물관, 갤러리, 문화 공간 등 전시와 문화 콘텐츠를 관람하는 장소입니다. */
  EXHIBITION_CULTURE,

  /** 영화관, 연극장, 뮤지컬 극장, 공연장 등 영화나 공연을 관람하는 장소입니다. */
  MOVIE_PERFORMANCE,

  /** 도예, 향수 제작, 베이킹, 원데이 클래스 등 직접 참여하여 결과물을 만드는 체험 장소입니다. */
  EXPERIENCE_WORKSHOP,

  /** 방탈출, 보드게임, 볼링, 클라이밍, 놀이공원 등 놀이와 신체 활동을 즐기는 장소입니다. */
  PLAY_ACTIVITY,

  /** 공원, 수목원, 해변, 산책로 등 자연을 감상하거나 산책하며 시간을 보내는 장소입니다. */
  NATURE_WALK,

  /** 편집숍, 소품숍, 시장, 쇼핑 중심 팝업스토어 등 상품을 둘러보거나 구매하는 장소입니다. */
  SHOPPING,

  /** 전망대, 야경 명소, 관광 명소 등 경관을 감상하거나 방문 자체에 의미가 있는 장소입니다. */
  LANDMARK_VIEW,

  /** 스파, 찜질방, 족욕 시설 등 몸과 마음의 휴식을 주된 목적으로 하는 장소입니다. */
  RELAXATION_SPA
}
