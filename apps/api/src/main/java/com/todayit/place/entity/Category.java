package com.todayit.place.entity;

/** 장소를 이용 목적과 성격에 따라 구분하는 상위 카테고리입니다. */
public enum Category {

  /** 한식, 양식, 일식, 중식, 분식, 브런치 등 음식점입니다. 술집·바는 하위 분류로 포함합니다. */
  RESTAURANT,

  /** 카페, 베이커리, 디저트 전문점, 제과점입니다. */
  CAFE_DESSERT,

  /** 미술관, 박물관, 갤러리, 전시 공간입니다. */
  EXHIBITION_MUSEUM,

  /** 연극장, 뮤지컬 극장, 공연장입니다. 영화관과 영화 상영 일정은 자동 포함하지 않습니다. */
  PERFORMANCE,

  /** 원천에 등록된 공방, 도예·향수·베이킹 체험, 원데이 클래스 등 체험 시설입니다. */
  EXPERIENCE,

  /** 테마파크, 놀이공원, 레저·스포츠 시설입니다. 방탈출·보드게임 공급 여부는 표본 확인이 필요합니다. */
  PLAY_LEISURE,

  /** 공원, 수목원, 해변, 산책로입니다. */
  NATURE_WALK,

  /** 시장, 쇼핑 시설, 상점입니다. 개별 편집숍·소품숍·팝업의 수집 범위는 별도 확인합니다. */
  SHOPPING,

  /** 전망대, 야경 명소, 관광 명소입니다. */
  LANDMARK_VIEW
}
